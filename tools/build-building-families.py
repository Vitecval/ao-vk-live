#!/usr/bin/env python3
"""Build the architecture eligibility table from public family/identity metadata.

Family dependencies come from reviewed model inventories, not filename guesses.
The deny list also contains inferred/scanned architecture so unfinished repaints
retain their original appearance. Personal overrides are handled by the loader.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


MAP_BITS={'d':1,'n':2,'orm':4,'e':8,'h':16}


def resolve(manifest):
    """Inventory shared ownership; masks describe artwork relationships, never GPU draw readiness."""
    entries={};graph={f['id']:{f['id']} for f in manifest['families']}
    assert len(graph)==len(manifest['families']), 'Duplicate family identity'
    for family in manifest['families']:
        number = family['id']
        assert 0 < number < 64
        declared={x['id']:x for x in family.get('resources',[])}
        assert not declared or set(declared)==set(family['texture_ids']), ('Incomplete resource declarations',family['key'])
        for identity in family['texture_ids']:
            assert identity not in entries, ('Resource must have one owner; declare shared_texture_ids on other families', identity)
            resource=declared.get(identity,{'id':identity,'pack':'ao-cyber-world','maps':['d','n','orm']})
            assert resource['pack'] in ('ao-cyber-world','ao-cyber-icc')
            assert resource['maps'] and set(resource['maps'])<=MAP_BITS.keys()
            entries[identity]={'family':number,'pack':resource['pack'],'maps':sum(MAP_BITS[s] for s in set(resource['maps']))}
    for family in manifest['families']:
        shared=set(family.get('shared_texture_ids',[]));own=set(family['texture_ids'])
        assert not shared&own
        for identity in shared:
            assert identity in entries, ('Missing shared resource owner',identity)
            owner=entries[identity]['family']
            graph[family['id']].add(owner);graph[owner].add(family['id'])
        allowed = own | shared | set(family['retained_functional_ids']) | set(family.get('pending_companion_ids',[]))
        for mesh in family['models']:
            assert set(mesh['textures']) <= allowed, (family['name'], mesh['mesh_id'], 'incomplete dependency inventory')
    masks={}
    for number in graph:
        reached=set();todo=[number]
        while todo:
            current=todo.pop()
            if current in reached:continue
            reached.add(current);todo.extend(graph[current]-reached)
        masks[number]=sum(1<<i for i in reached)
    return entries,masks


def main():
    manifest = json.loads((ROOT / 'material-packs/building-families.json').read_text())
    entries,masks=resolve(manifest)
    managed = set(entries)
    managed.update(i for f in manifest['families'] for i in f['retained_functional_ids'])
    managed.update(i for f in manifest['families'] for i in f.get('pending_companion_ids',[]))
    managed.update(x['id'] for x in json.loads((ROOT / 'material-packs/ao-world-materials/catalog.json').read_text()))
    managed.update(x['id'] for x in json.loads((ROOT / 'material-packs/scan-coverage.json').read_text())['textures']
                   if x['type'] == 1010004 and x['phase'] == 2)
    out = ['// Generated by tools/build-building-families.py; identity metadata only.',
           '#pragma once', '#include <algorithm>', '#include <cstdint>', '#include <iterator>',
           'namespace rvk::buildings {',
           'struct Resource { uint32_t id, family, maps; const char* pack; };', 'inline constexpr Resource resources[] = {']
    out += [f'    {{{identity}u, {resource["family"]}u, {resource["maps"]}u, "{resource["pack"]}"}},' for identity, resource in sorted(entries.items())]
    out += ['};', 'inline constexpr uint32_t managed[] = {']
    out += ['    ' + ','.join(f'{x}u' for x in sorted(managed)[i:i+16]) + ',' for i in range(0, len(managed), 16)]
    count=max(masks)+1
    out += ['};', f'inline constexpr uint32_t familyCount = {count}u;',
            'inline constexpr uint64_t readinessMasks[] = {' + ','.join(f'{masks.get(i,0)}ull' for i in range(count)) + '};',
            'inline uint64_t ReadinessMask(uint32_t family) { return family < familyCount ? readinessMasks[family] : 0; }',
            'inline bool WorldType(uint32_t type) { return type == 1010004 || type == 1010016 || type == 1010017; }',
            'inline const Resource* ResourceOf(uint32_t type, uint32_t id) {',
            '    if (!WorldType(type)) return nullptr;',
            '    auto it = std::lower_bound(std::begin(resources), std::end(resources), id,',
            '                               [](const Resource& x, uint32_t key) { return x.id < key; });',
            '    return it != std::end(resources) && it->id == id ? it : nullptr;', '}',
            'inline uint32_t FamilyOf(uint32_t type, uint32_t id) {',
            '    const auto* r=ResourceOf(type,id); return r ? r->family : 0;', '}',
            'inline bool Managed(uint32_t type, uint32_t id) {',
            '    return WorldType(type) && std::binary_search(std::begin(managed), std::end(managed), id);',
            '}', '}']
    (ROOT / 'rvk/building_families.h').write_text('\n'.join(out) + '\n')
    print(f'{len(entries)} family surfaces; {len(managed)} managed architecture identities')


if __name__ == '__main__':
    main()
