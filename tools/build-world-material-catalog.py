#!/usr/bin/env python3
"""Classify named architecture for the global material/detail pass, not repaints.

Import public texture identity/name metadata with --names and --index. The normal
build only needs the resulting catalog.json and generated C++ table.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / 'material-packs/ao-world-materials'
PROFILES = {'stone': (1, .84, 0), 'metal': (2, .34, .78), 'window': (3, .42, .45),
            'painted-metal': (4, .48, .16), 'brick': (5, .88, 0), 'wood': (6, .76, 0),
            'mineral': (7, .96, 0), 'honed-stone': (8, .88, 0)}
EXCLUDE = re.compile(r'armor|armour|helmet|head_|face|body|chest|pants|legs|boot|glove|sleeve|weapon|rifle|pistol|sword|skin|tree|leaf|leaves|bark|palm|flower|grass|particle|smoke|cloud|reflection|water|icon|symbol|cursor|fx_|effect|monster|creature', re.I)
ARCH = re.compile(r'building|window|glass|wall|roof|facade|concrete|cement|brick|plaster|midtech|hitech|plateyell|neutral_newplate|tile|floor|door|ceiling|pillar|column|tower|bridge|shop|store|booth|station|railing|stairs|stair|girder|metal|vent|grille|pipe|cladding|beam|asphalt|paving|pavement|street|shed|hut_', re.I)


def classify(name):
    if EXCLUDE.search(name): return None
    # Natural mineral surfaces must never inherit a metal or polished-window
    # guess. Shadowlands uses many shared rock and pale temple base atlases.
    if re.search(r'(^|[_ -])(rock|cliff|boulder|lava|basalt|sandstone|limestone)|shadowlandrock|lavarock|crackedrock|mount\d',name,re.I):
        return 'mineral'
    if re.search(r'marble|redeemed.*base_texture|overgang_cracked|jobe.*(?:plaster|stone)|wh_tile\d+_white',name,re.I):
        return 'honed-stone'
    if not ARCH.search(name): return None
    if re.search(r'window|glass', name, re.I): return 'window'
    if re.search(r'brick', name, re.I): return 'brick'
    if re.search(r'wood|timber|plank', name, re.I): return 'wood'
    if re.search(r'concrete|cement|stone|plaster|paving|pavement|asphalt', name, re.I): return 'stone'
    if re.search(r'metal|pipe|grille|girder|vent|beam|railing', name, re.I): return 'metal'
    if re.search(r'plate|midtech|hitech|door', name, re.I): return 'painted-metal'
    return 'stone'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--names', type=Path)
    parser.add_argument('--index', type=Path)
    args = parser.parse_args()
    PACK.mkdir(exist_ok=True)
    if args.names:
        names = json.loads(args.names.read_text())
        index = json.loads(args.index.read_text()) if args.index else names
        character = {(x['type'],x['id']) for x in json.loads((ROOT / 'material-packs/ao-character-materials/catalog.json').read_text())}
        catalog = []
        for key, name in names.items():
            kind, identity = map(int, key.split(':'))
            profile = classify(name)
            if kind != 1010004 or key not in index or (kind, identity) in character or profile is None: continue
            catalog.append({'type': kind, 'id': identity, 'name': name, 'profile': profile})
        catalog.sort(key=lambda x: (x['type'], x['id']))
        (PACK / 'catalog.json').write_text(json.dumps(catalog, indent=2) + '\n')
    else:
        catalog = json.loads((PACK / 'catalog.json').read_text())
    lines = ['// Generated by tools/build-world-material-catalog.py. Material metadata, not replacement art.']
    for x in catalog:
        kind, rough, metal = PROFILES[x['profile']]
        packed = round(rough * 255) | round(metal * 255) << 8 | kind << 24
        lines.append(f"    {{0x{(x['type'] << 32 | x['id']):016x}ull, 0x{packed:08x}u}},")
    (ROOT / 'rvk/world_material_catalog.inc').write_text('\n'.join(lines) + '\n')
    print(f'{len(catalog)} architecture material assignments; zero additional texture images')


if __name__ == '__main__': main()
