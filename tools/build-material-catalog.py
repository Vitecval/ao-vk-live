#!/usr/bin/env python3
"""Build the first character/equipment material catalog without copying game artwork.

Import with --names-json and optional --index-json from a local inventory. The
exported catalog is sufficient to reproduce the runtime include on any machine.
Unknown names stay unassigned; mixed outfits use a conservative non-metal profile.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'material-packs/ao-character-materials/catalog.json'
OUTPUT = ROOT / 'rvk/material_catalog.inc'
PROFILES = {
    'skin': (.56, 0), 'hair': (.78, 0), 'cloth': (.86, 0),
    'leather': (.49, 0), 'rubber': (.66, 0), 'polymer': (.43, 0),
    'painted_metal': (.34, .30), 'steel': (.25, .72),
    'organic': (.76, 0), 'bone': (.65, 0), 'wood': (.82, 0),
    'mixed_outfit': (.68, 0),
}


def classify(name, kind):
    name = name.lower()
    # Names with these uses are not character surface materials, even when they mention weapons or armour.
    if re.search(r'(^|[_\W])(sign|shop|terminal|statue|poster|banner|logo|icon|menu|particle|beam|glow|opacity|alpha|windmill|wall|floor|rack|vending|env)([_\W]|$)', name):
        return None
    if 'dont_use' in name:
        return None
    body = bool(re.match(r'(body|arms|legs|hands|feet|head|helmet|shoulders?|shoulderpads|backpack|back|hood|cloak|addonarmou?r)[_\d-]', name))
    if name.startswith(('ai_', 'ep03_')) and re.search(r'[_-](body|arms|legs|hands|feet|helmet)([_\W]|$)', name):
        body = True
    weapon = bool(re.search(r'(^|[_\W])(weapons?|rifle|pistol|shotgun|smg|sword|katana|carbine|axe|hammer|hellspinner|perennium|blaster|crossbow)\d*([_\W]|$)', name))
    if not body and not weapon:
        return None
    scope = 'equipment' if weapon or name.startswith(('helmet_', 'shoulder_', 'back_')) else 'character'
    race = r'(solitus|opifex|nanomage|at[hr]+ox)'
    if re.search(race, name) and (re.search(r'naked|default', name) or name.startswith('head_')):
        return 'skin', scope, 'race base skin'
    if 'hair' in name and body:
        return 'hair', scope, 'hair'
    if any(x in name for x in ('tongue', 'mouth', 'mutant', 'monster', 'mantis', 'tarasque', 'biomech', 'organic', 'dragonarmor')):
        return 'organic', scope, 'organic surface'
    if 'bone' in name:
        return 'bone', scope, 'bone'
    if 'wood' in name or (weapon and ('bow' in name or 'tonfa' in name)):
        return 'wood', scope, 'wooden equipment'
    if 'leather' in name or 'boots' in name or 'pumps' in name:
        return 'leather', scope, 'leather'
    if 'rubber' in name:
        return 'rubber', scope, 'rubber'
    if any(x in name for x in ('agility_sense', 'c6_scout')):
        return 'polymer', scope, 'composite scout equipment'
    if ('steel' in name and 'plasteel' not in name) or any(x in name for x in ('energizedmetal', 'nailarmour', 'chainmail')):
        return 'steel', scope, 'metal equipment'
    if any(x in name for x in ('plasteel', 'cyberarm', 'techarm', 'nanoarm', 'omnicop', 'omnisoldier', 'ofab', 'metald', 'addonarmour', 'shoulderpads_pande', 'hover_shoulder')):
        return 'painted_metal', scope, 'armour coating'
    if any(x in name for x in ('metaplast', 'plastic', 'carbonum', 'carbonfiber')):
        return 'polymer', scope, 'polymer armour'
    if any(x in name for x in ('shirt', 'pants', 'dress', 'suit', 'robe', 'cloak', 'hood', 'backpack', 'mafia', 'tuxedo', 'bureaucrat', 'kevlar', 'omnimed', 'bartender', 'martialartist', 'cloth', 'uniform', 'tshirt', 'skirt', 'clad')):
        return 'cloth', scope, 'textile clothing'
    if weapon:
        return 'painted_metal', scope, 'weapon housing'
    if kind == 1010011:
        return None  # unrecognised base skins are never guessed to be metallic armour
    return 'mixed_outfit', scope, 'unresolved character surface; non-metal baseline'


def render(catalog):
    lines = ['// Generated by tools/build-material-catalog.py. IDs and material parameters only; no game artwork.',
             '// Sorted by full-quality RDB type and ID. {key, roughness | metallic << 8}.']
    for item in catalog:
        rough, metal = PROFILES[item['profile']]
        packed = int(rough * 255 + .5) | (int(metal * 255 + .5) << 8)
        key = (item['type'] << 32) | item['id']
        lines.append(f'{{0x{key:016x}ull, 0x{packed:04x}u}},')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--names-json', type=Path)
    parser.add_argument('--index-json', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.names_json:
        names = json.loads(args.names_json.read_text())
        index = json.loads(args.index_json.read_text()) if args.index_json else None
        catalog = []
        for key, name in names.items():
            kind, identity = map(int, key.split(':'))
            if kind not in (1010004, 1010011) or (index is not None and key not in index):
                continue
            result = classify(name, kind)
            if result:
                profile, scope, rule = result
                catalog.append(dict(type=kind, id=identity, name=name, profile=profile, scope=scope, rule=rule))
        catalog.sort(key=lambda x: (x['type'], x['id']))
        CATALOG.parent.mkdir(parents=True, exist_ok=True)
        CATALOG.write_text(json.dumps(catalog, indent=2) + '\n')
    else:
        catalog = json.loads(CATALOG.read_text())
    keys = [(x['type'], x['id']) for x in catalog]
    assert keys == sorted(set(keys)), 'Catalog must have unique, sorted keys'
    result = render(catalog)
    if args.check:
        assert OUTPUT.read_text() == result, 'Rebuild material_catalog.inc'
    else:
        OUTPUT.write_text(result)
    print(f'{len(catalog)} assignments; profiles: {dict(Counter(x["profile"] for x in catalog))}')


if __name__ == '__main__':
    main()
