"""Regenerate the explicit exterior-glazing registry. No texture-name guessing."""
from pathlib import Path
import json,sys
S=Path(__file__).resolve().parents[1]
data=json.loads((S/'assets/window-profiles/catalog.json').read_text(encoding='utf-8'))
profiles=data['profiles'];panes=[];entries=[];witnesses=[]
for p in profiles:
 for mode,key in enumerate(['stock','authored']):
  first=len(panes);panes+=p[key];entries.append([p['id'],first,len(p[key]),p['flags'],mode])
 for m in p['models']:witnesses.append((p['id'],m['type'],m['id']))
def vec(v):return '{'+','.join(f'{float(x):.6f}f' for x in v)+'}'
header='''// Generated by build-registry.py from the explicit local artwork/model review.
// Optional exterior illusion only; real transparent views/opaque shutters remain.
#pragma once
#include <algorithm>
#include <cstdint>
#include <iterator>
namespace rvk::environment {
struct WindowPaneData {float rect[4],aperture[4],params[4];};
static_assert(sizeof(WindowPaneData)==48);
inline constexpr WindowPaneData windowPaneData[]={
'''
header+='\n'.join(' {'+','.join(vec(p[k]) for k in ['rect','aperture','params'])+'},' for p in panes)
header+='''
};
struct GlobalWindowProfile {uint32_t id,first,count,flags,authored;bool modelGuard=true;};
inline constexpr GlobalWindowProfile globalWindowProfiles[]={
'''
header+='\n'.join(' {'+','.join(map(str,e))+'},' for e in entries)
header+='''
};
inline const GlobalWindowProfile* GlobalWindowProfileOf(uint32_t type,uint32_t id,bool authored){
 if(type!=1010004&&type!=1010016&&type!=1010017)return nullptr;
 auto p=std::lower_bound(std::begin(globalWindowProfiles),std::end(globalWindowProfiles),id,[](const auto& a,uint32_t b){return a.id<b;});
 return p!=std::end(globalWindowProfiles)&&p->id==id?p+(authored?1:0):nullptr;
}
struct WindowModelWitness {uint32_t texture,type,model;};
inline constexpr WindowModelWitness windowModelWitnesses[]={
'''
header+='\n'.join(' {'+','.join(map(str,w))+'},' for w in sorted(set(witnesses)))
header+='''
};
inline bool GlobalWindowModelAllowed(uint32_t texture,uint32_t type,uint32_t model){
 auto p=std::lower_bound(std::begin(windowModelWitnesses),std::end(windowModelWitnesses),texture,[](const auto& a,uint32_t b){return a.texture<b;});
 for(;p!=std::end(windowModelWitnesses)&&p->texture==texture;++p)if(p->type==type&&p->model==model)return true;
 return false;
}
}
'''
# Shared neutral/clan/Omni artwork chooses style from positive model identity.
corporate=[(p['id'],m['type'],m['id']) for p in profiles for m in p['models'] if m.get('corporate')]
header=header[:-2]+"inline bool GlobalWindowCorporateModel(uint32_t texture,uint32_t type,uint32_t model){\n return "+' || '.join(f'(texture=={a}u&&type=={b}u&&model=={c}u)' for a,b,c in corporate)+";\n}\n}\n"
target=S/'rvk/window_global.h'
if '--check' in sys.argv:
 assert target.read_text(encoding='utf-8')==header,'Reviewed window header is stale'
 print('Reviewed window profiles are current')
else:target.write_text(header,encoding='utf-8')
